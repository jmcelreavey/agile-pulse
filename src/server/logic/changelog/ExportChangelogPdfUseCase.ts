import { AuthenticatedUseCase } from "~/server/logic/useCase";

interface ExportChangelogPdfInput {
  sprintId: number;
  content: string;
  projectName: string;
  sprintName: string;
}

export class ExportChangelogPdfUseCase extends AuthenticatedUseCase {
  async execute(input: ExportChangelogPdfInput) {
    const { sprintId, content, projectName, sprintName } = input;

    // Generate HTML content for the PDF
    const htmlContent = this.generatePdfHtml(content, projectName, sprintName);
    
    try {
      
      // Update the changelog to mark it as exported to PDF
      const changelog = await this.db.changelog.findFirst({
        where: { sprintId },
      });

      if (changelog) {
        await this.db.changelog.update({
          where: { id: changelog.id },
          data: {
            exportedToPdf: true,
            sharedAt: changelog.sharedAt ?? new Date(),
          },
        });

        // Track PDF export in sharing history
        await this.db.changelogSharing.create({
          data: {
            changelogId: changelog.id,
            customerId: null,
            method: "PDF_EXPORT",
            sharedBy: this.user.id,
            status: "sent",
          },
        });
      }

      return {
        success: true,
        fileName: `${projectName}-${sprintName}-Changelog`,
        html: htmlContent,
        mimeType: "text/html",
      };
    } catch (error) {
      console.error('PDF generation failed:', error);
      throw new Error('Failed to generate PDF. Please try again later.', { cause: error });
    }
  }

  private generatePdfHtml(content: string, projectName: string, sprintName: string): string {
    const currentDate = new Date().toLocaleDateString();
    
    return `
<!DOCTYPE html>
<html>
<head>
    <meta charset="utf-8">
    <title>${projectName} - ${sprintName} Changelog</title>
    <style>
        body {
            font-family: Arial, sans-serif;
            line-height: 1.6;
            max-width: 800px;
            margin: 0 auto;
            padding: 20px;
            color: #333;
        }
        .header {
            border-bottom: 2px solid #007bff;
            margin-bottom: 30px;
            padding-bottom: 20px;
        }
        .title {
            color: #007bff;
            font-size: 24px;
            font-weight: bold;
            margin: 0;
        }
        .subtitle {
            color: #666;
            font-size: 16px;
            margin: 5px 0 0 0;
        }
        .meta {
            background: #f8f9fa;
            padding: 15px;
            border-radius: 5px;
            margin: 20px 0;
            border-left: 4px solid #007bff;
        }
        .content {
            margin-top: 30px;
        }
        .footer {
            margin-top: 50px;
            padding-top: 20px;
            border-top: 1px solid #ddd;
            font-size: 12px;
            color: #666;
            text-align: center;
        }
    </style>
</head>
<body>
    <div class="header">
        <h1 class="title">${projectName}</h1>
        <p class="subtitle">${sprintName} - Sprint Changelog</p>
    </div>
    
    <div class="meta">
        <strong>Generated:</strong> ${currentDate}<br>
        <strong>Project:</strong> ${projectName}<br>
        <strong>Sprint:</strong> ${sprintName}
    </div>
    
    <div class="content">
        ${content}
    </div>
    
    <div class="footer">
        Generated by Agile Pulse - Project Management System
    </div>
</body>
</html>`;
  }
}
