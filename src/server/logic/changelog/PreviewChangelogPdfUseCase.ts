import { AuthenticatedUseCase } from "~/server/logic/useCase";

interface PreviewChangelogPdfInput {
  sprintId: number;
  content: string;
  projectName: string;
  sprintName: string;
}

export class PreviewChangelogPdfUseCase extends AuthenticatedUseCase {
  async execute(input: PreviewChangelogPdfInput) {
    const { content, projectName, sprintName } = input;

    // Generate HTML content for the PDF
    const htmlContent = this.generatePdfHtml(content, projectName, sprintName);
    
    try {
      
      return {
        success: true,
        fileName: `${projectName}-${sprintName}-Changelog-Preview`,
        html: htmlContent,
        mimeType: "text/html",
      };
    } catch (error) {
      console.error('PDF generation failed:', error);
      throw new Error('Failed to generate PDF preview. Please try again later.', { cause: error });
    }
  }

  private generatePdfHtml(content: string, projectName: string, sprintName: string): string {
    const currentDate = new Date().toLocaleDateString();
    
    return `
<!DOCTYPE html>
<html>
<head>
    <meta charset="utf-8">
    <title>${projectName} - ${sprintName} Changelog</title>
    <style>
        body {
            font-family: Arial, sans-serif;
            line-height: 1.6;
            max-width: 800px;
            margin: 0 auto;
            padding: 20px;
            color: #333;
        }
        .header {
            border-bottom: 2px solid #007bff;
            margin-bottom: 30px;
            padding-bottom: 20px;
        }
        .title {
            color: #007bff;
            font-size: 24px;
            font-weight: bold;
            margin: 0;
        }
        .subtitle {
            color: #666;
            font-size: 16px;
            margin: 5px 0 0 0;
        }
        .meta {
            background: #f8f9fa;
            padding: 15px;
            border-radius: 5px;
            margin: 20px 0;
            border-left: 4px solid #007bff;
        }
        .content {
            margin-top: 30px;
        }
        .footer {
            margin-top: 50px;
            padding-top: 20px;
            border-top: 1px solid #ddd;
            font-size: 12px;
            color: #666;
            text-align: center;
        }
        .preview-badge {
            background: #ffc107;
            color: #000;
            padding: 5px 10px;
            border-radius: 3px;
            font-size: 12px;
            font-weight: bold;
            display: inline-block;
            margin-bottom: 10px;
        }
    </style>
</head>
<body>
    <div class="preview-badge">DEVELOPER PREVIEW</div>
    <div class="header">
        <h1 class="title">${projectName}</h1>
        <p class="subtitle">${sprintName} - Sprint Changelog</p>
    </div>
    
    <div class="meta">
        <strong>Generated:</strong> ${currentDate}<br>
        <strong>Project:</strong> ${projectName}<br>
        <strong>Sprint:</strong> ${sprintName}
    </div>
    
    <div class="content">
        ${content}
    </div>
    
    <div class="footer">
        Generated by Agile Pulse - Project Management System<br>
        <em>This is a developer preview and does not count as official sharing</em>
    </div>
</body>
</html>`;
  }
}
